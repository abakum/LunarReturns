import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({ entryPoints: [path.join(root, 'dev/viewer.js')], bundle: true,
    write: false, minify: true, format: 'iife', target: 'es2020', metafile: true });
const packages = new Set();
for (const name of Object.keys(result.metafile.inputs)) {
    const match = name.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
    if (match) packages.add(match[1]);
}
let licenses = '';
for (const name of [...packages].sort()) {
    const dir = path.join(root, 'node_modules', name);
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const files = fs.readdirSync(dir).filter(n => /^(licen[sc]e|copying|notice)(\.|$)/i.test(n));
    if (!files.length) throw new Error('Missing license: ' + name);
    licenses += '\n' + name + '@' + pkg.version + '\n' + files.map(n => fs.readFileSync(path.join(dir, n), 'utf8')).join('\n');
}
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const output = '// Generated by npm run build:viewer; do not edit.\nmodule.exports = ' + JSON.stringify({ script, licenses }) + ';\n';
fs.writeFileSync(path.join(root, 'tgcloud/lib/viewer-bundle.cjs'), output);
fs.writeFileSync(path.join(root, 'docs/viewer-licenses.txt'), licenses);
console.log('viewer bundle:', Buffer.byteLength(output), 'bytes');
